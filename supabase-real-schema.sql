create or replace function real_guest_like_post(target_post_id uuid)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  next_likes integer;
begin
  update real_community_posts
  set likes = coalesce(likes, 0) + 1
  where id = target_post_id
  returning likes into next_likes;

  return coalesce(next_likes, 0);
end;
$$;

