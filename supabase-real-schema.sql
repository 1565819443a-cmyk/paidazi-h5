create or replace function real_like_post(target_post_id uuid)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  next_likes integer;
begin
  insert into real_post_likes(user_id, post_id)
  values (auth.uid(), target_post_id)
  on conflict do nothing;

  update real_community_posts
  set likes = (
    select count(*)::integer from real_post_likes where post_id = target_post_id
  )
  where id = target_post_id
  returning likes into next_likes;

  return coalesce(next_likes, 0);
end;
$$;

create or replace function real_increment_comments_count(target_post_id uuid)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  next_count integer;
begin
  update real_community_posts
  set comments_count = (
    select count(*)::integer from real_comments where post_id = target_post_id
  )
  where id = target_post_id
  returning comments_count into next_count;

  return coalesce(next_count, 0);
end;
$$;

