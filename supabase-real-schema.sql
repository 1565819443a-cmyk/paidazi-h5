-- π搭子真实数据版数据库结构
-- 用新的 real_* 表，避免影响当前 paidazi.cn 演示版使用的旧表。

create extension if not exists pgcrypto;

create table if not exists real_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  phone text,
  nickname text not null default 'π星人',
  avatar text not null default 'https://randomuser.me/api/portraits/lego/1.jpg',
  tags jsonb not null default '{}',
  personality_answers jsonb not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table real_profiles add column if not exists email text;

create table if not exists real_community_posts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null,
  category_name text not null,
  title text not null default '',
  content text not null,
  contact text not null default '',
  nickname text not null,
  avatar text not null,
  likes integer not null default 0,
  comments_count integer not null default 0,
  url text,
  link_text text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists real_comments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  post_id uuid not null references real_community_posts(id) on delete cascade,
  parent_id bigint references real_comments(id) on delete cascade,
  nickname text not null,
  avatar text not null,
  content text not null,
  to_nickname text,
  created_at timestamptz not null default now()
);

create table if not exists real_demands (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null,
  category_name text not null,
  title text not null default '',
  contact text not null default '',
  nickname text not null,
  avatar text not null,
  tags text[] not null default '{}',
  personality_answers jsonb not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists real_invites (
  id bigint generated by default as identity primary key,
  from_user_id uuid not null references auth.users(id) on delete cascade,
  from_nickname text not null,
  to_user_id uuid references auth.users(id) on delete set null,
  to_user text not null,
  demand_id bigint references real_demands(id) on delete cascade,
  status text not null default 'pending',
  content text not null default '邀请你一起学习',
  created_at timestamptz not null default now()
);

create table if not exists real_bookmarks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  post_id uuid not null references real_community_posts(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(user_id, post_id)
);

create table if not exists real_post_likes (
  user_id uuid not null references auth.users(id) on delete cascade,
  post_id uuid not null references real_community_posts(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(user_id, post_id)
);

